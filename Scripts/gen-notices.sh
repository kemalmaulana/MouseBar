#!/bin/bash
# Regenerates THIRD_PARTY_NOTICES.md. Usage: Scripts/gen-notices.sh
#
# Everything above the "gen-notices" marker line in THIRD_PARTY_NOTICES.md is hand-written and kept as is.
# Everything below it is rebuilt from `cargo metadata` for Rust/mousebar-logi (target aarch64-apple-darwin):
# a crate/version/licence table, then the licence texts found in each crate's source directory. Identical texts
# are printed once with the list of crates that ship them. Needs the crates' sources in ~/.cargo (any
# `cargo build` of the crate puts them there). Running it twice gives the same file.
set -euo pipefail
cd "$(dirname "$0")/.."

if ! command -v cargo >/dev/null 2>&1 && [ -f "$HOME/.cargo/env" ]; then
    . "$HOME/.cargo/env"
fi
if ! command -v cargo >/dev/null 2>&1; then
    echo "error: cargo not found. Install Rust with rustup: https://rustup.rs" >&2
    exit 1
fi

METADATA="$(mktemp)"
trap 'rm -f "$METADATA"' EXIT
cargo metadata --format-version 1 --locked --filter-platform aarch64-apple-darwin \
    --manifest-path Rust/mousebar-logi/Cargo.toml > "$METADATA"

python3 -I - "$METADATA" THIRD_PARTY_NOTICES.md <<'PY'
import json
import os
import sys

metadata_path, notices_path = sys.argv[1], sys.argv[2]
MARKER = "<!-- gen-notices: everything below this line is generated by Scripts/gen-notices.sh; edit above it only -->"
PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")
NOT_TEXT = (".rs", ".toml", ".json", ".yml", ".yaml", ".py", ".c", ".h", ".sh", ".lock")

with open(metadata_path, encoding="utf-8") as f:
    metadata = json.load(f)
in_graph = {node["id"] for node in metadata["resolve"]["nodes"]}
# The root crate (no source) is MouseBar's own code, not a third-party one.
crates = sorted(
    (p for p in metadata["packages"] if p["id"] in in_graph and p["source"]),
    key=lambda p: (p["name"], p["version"]),
)

with open(notices_path, encoding="utf-8") as f:
    existing = f.read()
head, found, _ = existing.partition(MARKER)
if not found:
    sys.exit("error: marker line not found in " + notices_path)


def licence_files(directory):
    names = []
    for name in os.listdir(directory):
        lower = name.lower()
        if (
            lower.startswith(PREFIXES)
            and not lower.endswith(NOT_TEXT)
            and os.path.isfile(os.path.join(directory, name))
        ):
            names.append(name)
    return sorted(names)


def find_licence_files(crate):
    directory = os.path.dirname(crate["manifest_path"])
    if not os.path.isdir(directory):
        sys.exit("error: source of %s %s is missing: %s" % (crate["name"], crate["version"], directory))
    names = licence_files(directory)
    # A crate inside a git workspace keeps its licence at the workspace root: walk up to the checkout root.
    if crate["source"].startswith("git+"):
        while not names and not os.path.exists(os.path.join(directory, ".git")):
            parent = os.path.dirname(directory)
            if parent == directory:
                break
            directory = parent
            names = licence_files(directory)
    return [os.path.join(directory, name) for name in names]


def normalized(path):
    with open(path, "rb") as f:
        text = f.read().decode("utf-8", errors="replace")
    text = text.replace("\r\n", "\n").replace("\r", "\n").lstrip("﻿")
    return "\n".join(line.rstrip() for line in text.split("\n")).strip("\n")


groups = {}  # text -> [crate labels]
without_text = []
for crate in crates:
    label = "%s %s" % (crate["name"], crate["version"])
    texts = []
    for path in find_licence_files(crate):
        text = normalized(path)
        if text and text not in texts:
            texts.append(text)
    if not texts:
        without_text.append(crate)
    for text in texts:
        groups.setdefault(text, []).append(label)


def fence_for(text):
    longest = run = 0
    for ch in text:
        run = run + 1 if ch == "`" else 0
        longest = max(longest, run)
    return "`" * max(3, longest + 1)


out = [head + MARKER, ""]
out += [
    "## Rust dependency tree of `Rust/mousebar-logi`",
    "",
    "Every crate Cargo resolves for the `aarch64-apple-darwin` target (name, version, licence as declared in its manifest). "
    "The licence texts follow in the next section. `Scripts/gen-notices.sh` writes both from "
    "`cargo metadata --format-version 1 --locked --filter-platform aarch64-apple-darwin --manifest-path Rust/mousebar-logi/Cargo.toml`.",
    "",
    "| Crate | Version | Licence |",
    "|---|---|---|",
]
for crate in crates:
    out.append("| %s | %s | %s |" % (crate["name"], crate["version"], crate["license"] or "see crate"))
out.append("")

out += [
    "## Licence texts",
    "",
    "The licence and notice files shipped with each crate above. Identical texts appear once, under the crates that ship them.",
    "",
]
ordered = sorted(groups.items(), key=lambda item: (item[1][0], item[0]))
for number, (text, labels) in enumerate(ordered, 1):
    fence = fence_for(text)
    out += ["### %d. %s" % (number, ", ".join(labels)), "", fence, text, fence, ""]

if without_text:
    out += [
        "## Crates without a licence file",
        "",
        "These crates ship no licence file in their source. Their declared licence and repository are:",
        "",
    ]
    for crate in without_text:
        out.append(
            "- %s %s: %s, %s"
            % (
                crate["name"],
                crate["version"],
                crate["license"] or "no licence declared",
                crate["repository"] or crate["homepage"] or "no repository declared",
            )
        )
    out.append("")

result = "\n".join(out).rstrip("\n") + "\n"
temporary = notices_path + ".tmp"
with open(temporary, "w", encoding="utf-8") as f:
    f.write(result)
os.replace(temporary, notices_path)
print("wrote %s: %d crates, %d distinct licence texts, %d crates without a licence file"
      % (notices_path, len(crates), len(groups), len(without_text)))
PY
